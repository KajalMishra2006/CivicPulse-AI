/**
 * Returns translation object for given language, with Proxy fallback to English.
 */
export function getTranslation(languageName = 'English') {
  const langKey = languageName || 'English'
  const langTranslations = TRANSLATIONS[langKey] || TRANSLATIONS.English

  return new Proxy(langTranslations, {
    get(target, prop) {
      if (typeof prop === 'string' && prop in target && target[prop]) {
        return target[prop]
      }
      if (typeof prop === 'string' && prop in TRANSLATIONS.English) {
        return TRANSLATIONS.English[prop]
      }
      return prop
    }
  })
}

/**
 * Helper to translate category names
 */
export function translateCategory(category, t) {
  if (!category) return ''
  const c = String(category).toLowerCase()
  if (c.includes('road') || c.includes('pothole')) return t.catRoads || t.roadsPotholes || category
  if (c.includes('garbage') || c.includes('sanitation')) return t.catGarbage || t.garbageSanitation || category
  if (c.includes('streetlight') || c.includes('street light')) return t.catStreetlight || t.streetlights || category
  if (c.includes('water')) return t.catWater || t.waterSupply || category
  if (c.includes('drainage') || c.includes('flood')) return t.catDrainage || t.drainageFlooding || category
  if (c.includes('electric') || c.includes('power')) return t.catElectricity || t.electricityPower || category
  if (c.includes('other')) return t.catOther || t.otherCivic || category
  return category
}

/**
 * Helper to translate status strings
 */
export function translateStatus(status, t) {
  if (!status) return t.statusPending || 'Pending'
  const s = String(status).toLowerCase()
  if (s.includes('in progress') || s.includes('inprogress') || s.includes('in-progress')) return t.statusInProgress || t.inProgress || 'In Progress'
  if (s.includes('resolve')) return t.statusResolved || t.resolved || 'Resolved'
  if (s.includes('reject')) return t.statusRejected || t.rejected || 'Rejected'
  return t.statusPending || t.pending || 'Pending'
}

/**
 * Helper to translate priority strings
 */
export function translatePriority(priority, t) {
  if (!priority) return t.priorityMedium || t.mediumPriority || 'Medium'
  const p = String(priority).toLowerCase()
  if (p.includes('high')) return t.priorityHigh || t.highPriority || 'High'
  if (p.includes('low')) return t.priorityLow || t.lowPriority || 'Low'
  return t.priorityMedium || t.mediumPriority || 'Medium'
}
